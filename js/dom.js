// Building page elements. Text is always added as text nodes (never parsed as HTML), so names
// and other data from the database cannot inject markup (XSS).

/** h('button', { class: 'primary', onclick: fn }, 'Save') → <button class="primary">Save</button> */
export function h(tag, attrs, ...kids) {
  const el = document.createElement(tag);
  const a = attrs || {};
  for (const [k, v] of Object.entries(a)) {
    if (v == null || v === false || k === 'value') continue;
    if (k.startsWith('on') && typeof v === 'function') el.addEventListener(k.slice(2).toLowerCase(), v);
    else if (k === 'class') el.className = v;
    else if (v === true) el.setAttribute(k, '');
    else el.setAttribute(k, v);
  }
  for (const c of kids.flat(Infinity)) if (c != null && c !== false) el.append(c instanceof Node ? c : String(c));
  if ('value' in a && a.value != null) el.value = a.value;
  return el;
}

/** replaceChildren that skips empty parts (null / false / 0 / '' from `cond && h(...)`). */
export function fill(el, ...kids) {
  el.replaceChildren(...kids.flat(Infinity).filter((c) => c != null && c !== false && c !== 0 && c !== ''));
}

